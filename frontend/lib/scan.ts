import type { Scan, Tech } from "./types";

export interface PipelineStep {
  id: string;
  title: string;
  active: string;
  done: string;
  ms: number;
}

export const PIPELINE_STEPS: PipelineStep[] = [
  { id: "fetch", title: "Fetching URL", active: "Resolving the host and downloading the page…", done: "Page downloaded", ms: 300 },
  { id: "render", title: "Rendering HTML (JavaScript)", active: "Executing page scripts…", done: "Page rendered", ms: 600 },
  { id: "fingerprint", title: "Fingerprinting Tech Stack", active: "Identifying frameworks, CDNs, build tools…", done: "Stack identified", ms: 900 },
  { id: "synthesize", title: "AI Synthesizing Documentation", active: "Writing the Markdown…", done: "Documentation written", ms: 1200 },
];

export const TOTAL_MS = PIPELINE_STEPS.reduce((sum, s) => sum + s.ms, 0);

export type StepState = "done" | "current" | "queued";

// Given how many ms have elapsed, returns the state ("done" | "current" | "queued") of each
// pipeline step in order, for the progress card. Pure calculation; stores nothing.
export function stepStates(elapsed: number): StepState[] {
  let start = 0;
  return PIPELINE_STEPS.map((s) => {
    const end = start + s.ms;
    const state: StepState = elapsed >= end ? "done" : elapsed >= start ? "current" : "queued";
    start = end;
    return state;
  });
}

// MOCK: deterministic stand-in data keyed on the host. Replace buildScan with a
// call to the real backend and keep the signature; nothing else needs to change.
const STACKS: [string, string][][] = [
  [["Framework", "Next.js 15"], ["Library", "React 19"], ["Hosting", "Vercel"], ["Styling", "Tailwind CSS"], ["Language", "TypeScript"]],
  [["Framework", "Nuxt 3"], ["Library", "Vue 3"], ["Hosting", "Cloudflare"], ["Build", "Vite"], ["Language", "TypeScript"]],
  [["Framework", "WordPress 6"], ["Language", "PHP 8"], ["Database", "MySQL"], ["CDN", "Cloudflare"], ["Library", "jQuery"]],
  [["Framework", "Astro 4"], ["Hosting", "Cloudflare Pages"], ["Styling", "Tailwind CSS"], ["Language", "TypeScript"]],
  [["Framework", "Django"], ["Language", "Python"], ["Database", "PostgreSQL"], ["Server", "Nginx"]],
];

// Turns text into a repeatable number (FNV-1a hash) so the same host always gets the same mock data. Stores nothing.
function hash(text: string): number {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 16777619);
  return h >>> 0;
}

// MOCK scan: builds a complete Scan object for a URL (id, url, host, date, duration, confidence,
// pages, tech list, markdown text) from the hostname hash. Makes no network request. The caller
// (ScanProvider) saves the returned Scan to history; this function stores nothing itself.
export function buildScan(url: string): Scan {
  const host = new URL(url).hostname.replace(/^www\./, "");
  const h = hash(host);
  const stack = STACKS[h % STACKS.length];
  const tech: Tech[] = stack.map(([, name], i) => ({ name, highlighted: i < 3 }));
  const confidence = 88 + (h % 12);
  const pages = 4 + (h % 20);
  const createdAt = new Date().toISOString();

  const markdown = [
    `# ${host} Documentation`,
    "",
    `> Generated by Project MD from ${url}`,
    "",
    "## Overview",
    "",
    `- **URL:** ${url}`,
    `- **Scanned:** ${createdAt.slice(0, 10)}`,
    `- **Pages documented:** ${pages}`,
    `- **Confidence:** ${confidence}%`,
    "",
    "## Tech Stack",
    "",
    ...stack.map(([label, name]) => `- **${label}:** ${name}`),
    "",
    "## Site Structure",
    "",
    "```",
    "├── /",
    "├── /docs",
    "├── /pricing",
    "└── /blog",
    "```",
    "",
  ].join("\n");

  return {
    id: crypto.randomUUID(),
    url,
    host,
    createdAt,
    durationMs: TOTAL_MS,
    confidence,
    pages,
    tech,
    markdown,
  };
}
