// MOCK: builds the sample Markdown document shown for a static (non-AI) scan. The site
// structure section is a fixed placeholder, not a crawl result. Stores nothing.
export function buildMockMarkdown(args: {
  host: string;
  url: string;
  createdAt: string;
  pages: number;
  confidence: number;
  stack: [string, string][];
}): string {
  const { host, url, createdAt, pages, confidence, stack } = args;
  return [
    `# ${host} Documentation`,
    "",
    `> Generated by Project MD from ${url}`,
    "",
    "## Overview",
    "",
    `- **URL:** ${url}`,
    `- **Scanned:** ${createdAt.slice(0, 10)}`,
    `- **Pages documented:** ${pages}`,
    `- **Confidence:** ${confidence}%`,
    "",
    "## Tech Stack",
    "",
    ...stack.map(([label, name]) => `- **${label}:** ${name}`),
    "",
    "## Site Structure",
    "",
    "```",
    "├── /",
    "├── /docs",
    "├── /pricing",
    "└── /blog",
    "```",
    "",
  ].join("\n");
}
