using System.Globalization;
using System.Text;
using ProjectMD.Api.Models;
using ProjectMD.Api.Services.Extraction;

namespace ProjectMD.Api.Services.Pipeline;

// How the document in a scan was produced. Decides the footer line at the bottom of the Markdown.
public enum ScanBasis
{
    // `extract` mode: built from the page structure only, no AI was ever asked.
    Extract,

    // The AI wrote the summary parts (fresh or from the cache).
    Ai,

    // `ai` mode, but no AI client is configured, so this is the same as Extract.
    AiNotConfigured,

    // `ai` mode, but a daily token cap was reached, so the AI was skipped.
    AiBudget,

    // `ai` mode, but the AI call failed or returned nothing usable, so the AI was skipped.
    AiFailed,
}

// Everything the Markdown builder needs for one scan.
public sealed record MarkdownInput(
    string Host,
    Uri RequestedUrl,
    DateTime ScannedOnUtc,
    PageDigest Digest,
    IReadOnlyList<ScanTech> Tech,
    int Confidence,
    int Pages,
    string? AiProse,
    ScanBasis Basis);

// Builds the whole scan document WITHOUT the AI, from what the free extraction code found. This is
// the output of `extract` mode and the fallback whenever the AI is off, over budget or failing.
// When the AI did write something, its short prose is inserted as one extra section; everything
// else (overview facts, tech list, outline, links) is always deterministic, so the AI never has to
// be paid to restate it.
public static class DeterministicMarkdownBuilder
{
    // Footer lines. Every fallback says "Basic scan" so it is easy to spot.
    public const string FooterExtract = "Basic scan: built from the page's own structure, without AI writing.";
    public const string FooterAi = "Summary written by AI from the page content above. Check details before relying on them.";
    public const string FooterNotConfigured = "Basic scan: AI writing is not configured.";
    public const string FooterBudget = "Basic scan: the daily AI budget was reached, so no AI writing was used.";
    public const string FooterFailed = "Basic scan: AI writing was unavailable for this scan.";

    // Caps that keep the document small however big the page is.
    private const int MaxTitleChars = 200;
    private const int MaxDescriptionChars = 400;
    private const int MaxOutlineItems = 60;
    private const int MaxLinkItems = 25;
    private const int MaxLinkTextChars = 120;
    private const int MaxHrefChars = 500;
    private const int MaxTechItems = 12;

    // Builds the Markdown document.
    public static string Build(MarkdownInput input)
    {
        ArgumentNullException.ThrowIfNull(input);
        var digest = input.Digest;
        var sb = new StringBuilder();

        sb.Append("# ").Append(Inline(input.Host, 255)).AppendLine(" Documentation").AppendLine();
        sb.Append("> Generated by Project MD from ").AppendLine(AutoLink(input.RequestedUrl)).AppendLine();

        // Overview: plain facts, each one known without the AI.
        sb.AppendLine("## Overview").AppendLine();
        sb.Append("- **URL:** ").AppendLine(AutoLink(input.RequestedUrl));
        if (!string.Equals(digest.FinalUrl.AbsoluteUri, input.RequestedUrl.AbsoluteUri, StringComparison.Ordinal))
        {
            sb.Append("- **Final URL:** ").AppendLine(AutoLink(digest.FinalUrl));
        }

        sb.Append("- **Scanned:** ").AppendLine(input.ScannedOnUtc.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture));
        sb.Append("- **Pages documented:** ").AppendLine(input.Pages.ToString(CultureInfo.InvariantCulture));
        sb.Append("- **Confidence:** ").Append(input.Confidence.ToString(CultureInfo.InvariantCulture))
            .AppendLine("% (a rough estimate of how much the page told us, not a measured accuracy)");
        AppendOptional(sb, "Title", digest.Title, MaxTitleChars);
        AppendOptional(sb, "Description", digest.MetaDescription, MaxDescriptionChars);
        AppendOptional(sb, "Language", digest.Language, 20);
        sb.AppendLine();

        // The AI's prose, when there is any.
        if (!string.IsNullOrWhiteSpace(input.AiProse))
        {
            sb.AppendLine("## About this site").AppendLine();
            sb.AppendLine(input.AiProse.Trim()).AppendLine();
        }

        // Tech stack from the fingerprinter.
        sb.AppendLine("## Tech Stack").AppendLine();
        var tech = input.Tech.Where(t => !string.IsNullOrWhiteSpace(t.Name)).Take(MaxTechItems).ToList();
        if (tech.Count == 0)
        {
            sb.AppendLine("_No technologies were recognised from the page._");
        }
        else
        {
            foreach (var t in tech)
            {
                var name = Inline(t.Name, 80);
                sb.AppendLine(t.Highlighted ? $"- **{name}**" : $"- {name}");
            }
        }

        sb.AppendLine();

        // Heading outline.
        sb.AppendLine("## Site Structure").AppendLine();
        AppendOutline(sb, digest.Outline);
        sb.AppendLine();

        // Top links.
        var links = digest.Links
            .Where(l => IsHttp(l.Href))
            .Take(MaxLinkItems)
            .ToList();
        if (links.Count > 0)
        {
            sb.AppendLine("## Key Links").AppendLine();
            foreach (var link in links)
            {
                var text = Inline(string.IsNullOrWhiteSpace(link.Text) ? link.Href : link.Text, MaxLinkTextChars);
                sb.Append("- [").Append(text).Append("](").Append(Destination(link.Href)).AppendLine(")");
            }

            sb.AppendLine();
        }

        sb.AppendLine("---").AppendLine();
        sb.Append('*').Append(FooterFor(input.Basis)).Append('*').AppendLine();

        // Always "\n", whatever operating system the server runs on (like the mock document).
        return sb.ToString().ReplaceLineEndings("\n");
    }

    // The footer sentence for how the document was produced.
    public static string FooterFor(ScanBasis basis) => basis switch
    {
        ScanBasis.Ai => FooterAi,
        ScanBasis.AiNotConfigured => FooterNotConfigured,
        ScanBasis.AiBudget => FooterBudget,
        ScanBasis.AiFailed => FooterFailed,
        _ => FooterExtract,
    };

    // Writes "- **Label:** value" when the value is not empty.
    private static void AppendOptional(StringBuilder sb, string label, string? value, int maxChars)
    {
        if (!string.IsNullOrWhiteSpace(value))
        {
            sb.Append("- **").Append(label).Append(":** ").AppendLine(Inline(value, maxChars));
        }
    }

    // The heading outline as a nested list, indented by level relative to the shallowest heading.
    private static void AppendOutline(StringBuilder sb, IReadOnlyList<HeadingNode> outline)
    {
        var headings = outline.Where(h => !string.IsNullOrWhiteSpace(h.Text)).Take(MaxOutlineItems).ToList();
        if (headings.Count == 0)
        {
            sb.AppendLine("_No headings were found on the page._");
            return;
        }

        var top = headings.Min(h => h.Level);
        foreach (var h in headings)
        {
            var depth = Math.Clamp(h.Level - top, 0, 5);
            sb.Append(' ', depth * 2).Append("- ").AppendLine(Inline(h.Text, 160));
        }
    }

    // True for an absolute http(s) address (the only links we put in the document).
    private static bool IsHttp(string href) =>
        Uri.TryCreate(href, UriKind.Absolute, out var uri)
        && (uri.Scheme == Uri.UriSchemeHttp || uri.Scheme == Uri.UriSchemeHttps);

    // One line of text made safe for Markdown: whitespace collapsed, cut to `maxChars`, and the
    // characters that could start formatting, a link, an image or HTML are escaped with a backslash.
    private static string Inline(string? text, int maxChars)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return string.Empty;
        }

        var sb = new StringBuilder();
        var lastWasSpace = true;
        foreach (var c in text)
        {
            if (sb.Length >= maxChars)
            {
                sb.Append('…');
                break;
            }

            if (char.IsWhiteSpace(c) || char.IsControl(c))
            {
                if (!lastWasSpace)
                {
                    sb.Append(' ');
                }

                lastWasSpace = true;
                continue;
            }

            lastWasSpace = false;
            if ("\\`*_[]<>|#&".Contains(c))
            {
                sb.Append('\\');
            }

            sb.Append(c);
        }

        return sb.ToString().TrimEnd();
    }

    // A page address shown as plain text: an autolink (<https://...>) so Markdown viewers make it
    // clickable and leave "_" and "*" alone. Addresses that cannot be an autolink (they hold a
    // space, angle bracket or backslash) are shown in a code span instead.
    private static string AutoLink(Uri uri)
    {
        var text = uri.AbsoluteUri;
        return text.IndexOfAny(['<', '>', ' ', '\\', '\n', '\r']) < 0
            ? "<" + text + ">"
            : "`" + text.Replace("`", "%60", StringComparison.Ordinal) + "`";
    }

    // A web address made safe to put inside "(...)" of a Markdown link: control characters,
    // spaces, parentheses, angle brackets and backslashes are percent-encoded, and it is cut at a
    // sane length.
    private static string Destination(string href)
    {
        var clean = href.Length > MaxHrefChars ? href[..MaxHrefChars] : href;
        var sb = new StringBuilder(clean.Length);
        foreach (var c in clean)
        {
            if (c <= ' ' || c == 127 || "()<>\\".Contains(c))
            {
                sb.Append('%').Append(((int)c).ToString("X2", CultureInfo.InvariantCulture));
            }
            else
            {
                sb.Append(c);
            }
        }

        return sb.ToString();
    }
}
