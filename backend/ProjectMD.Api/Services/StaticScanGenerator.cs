using System.Globalization;
using ProjectMD.Api.Models;

namespace ProjectMD.Api.Services;

// MOCK generator (the default): a port of frontend/app/functions/data/static/mock-scan.ts,
// mock-markdown.ts and mock-stacks.ts. It makes no network request and uses no AI. Every value
// is deterministic stand-in data derived from a hash of the host, NOT a measurement of the site:
// the same host always gets the same tech stack, confidence and page count.
public sealed class StaticScanGenerator : IScanGenerator
{
    // The mock "scan duration": the frontend's TOTAL_MS (300 + 600 + 900 + 1200). Not measured.
    public const int MockDurationMs = 3000;

    // MOCK: stand-in tech stacks as (category label, technology name) pairs, copied from
    // mock-stacks.ts. NOT measured from any real site.
    private static readonly (string Label, string Name)[][] MockStacks =
    [
        [("Framework", "Next.js 15"), ("Library", "React 19"), ("Hosting", "Vercel"), ("Styling", "Tailwind CSS"), ("Language", "TypeScript")],
        [("Framework", "Nuxt 3"), ("Library", "Vue 3"), ("Hosting", "Cloudflare"), ("Build", "Vite"), ("Language", "TypeScript")],
        [("Framework", "WordPress 6"), ("Language", "PHP 8"), ("Database", "MySQL"), ("CDN", "Cloudflare"), ("Library", "jQuery")],
        [("Framework", "Astro 4"), ("Hosting", "Cloudflare Pages"), ("Styling", "Tailwind CSS"), ("Language", "TypeScript")],
        [("Framework", "Django"), ("Language", "Python"), ("Database", "PostgreSQL"), ("Server", "Nginx")],
    ];

    private readonly TimeProvider _clock;

    // Receives the clock used for the "Scanned" date in the sample document.
    public StaticScanGenerator(TimeProvider clock)
    {
        _clock = clock;
    }

    // MOCK: builds the stand-in scan for a URL from its host. Completes synchronously.
    public Task<GeneratedScan> GenerateAsync(Uri url, CancellationToken ct)
    {
        ct.ThrowIfCancellationRequested();

        var host = UrlValidator.DisplayHost(url);
        var h = Hash(host);
        var stack = MockStacks[h % (uint)MockStacks.Length];

        var tech = stack
            .Select((entry, index) => new ScanTech { Name = entry.Name, Highlighted = index < 3 })
            .ToList();
        var confidence = 88 + (int)(h % 12);
        var pages = 4 + (int)(h % 20);
        var scannedOn = _clock.GetUtcNow().UtcDateTime;
        var markdown = BuildMarkdown(host, url.AbsoluteUri, scannedOn, pages, confidence, stack);

        return Task.FromResult(new GeneratedScan(MockDurationMs, confidence, pages, tech, markdown));
    }

    // Turns text into a repeatable number (32-bit FNV-1a over the UTF-16 characters, exactly like
    // the frontend's hash()) so the same host always gets the same mock data.
    public static uint Hash(string text)
    {
        unchecked
        {
            uint h = 2166136261;
            foreach (var c in text)
            {
                h = (h ^ c) * 16777619;
            }

            return h;
        }
    }

    // MOCK: the sample Markdown document (same lines as mock-markdown.ts). The site structure
    // section is a fixed placeholder, not a crawl result.
    private static string BuildMarkdown(
        string host,
        string url,
        DateTime scannedOn,
        int pages,
        int confidence,
        (string Label, string Name)[] stack)
    {
        var lines = new List<string>
        {
            $"# {host} Documentation",
            "",
            $"> Generated by Project MD from {url}",
            "",
            "## Overview",
            "",
            $"- **URL:** {url}",
            $"- **Scanned:** {scannedOn.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)}",
            $"- **Pages documented:** {pages}",
            $"- **Confidence:** {confidence}%",
            "",
            "## Tech Stack",
            "",
        };
        lines.AddRange(stack.Select(entry => $"- **{entry.Label}:** {entry.Name}"));
        lines.AddRange(
        [
            "",
            "## Site Structure",
            "",
            "```",
            "├── /",
            "├── /docs",
            "├── /pricing",
            "└── /blog",
            "```",
            "",
        ]);

        return string.Join("\n", lines);
    }
}
