using ProjectMD.Api.Services;

namespace ProjectMD.Api.Tests.Scans;

// Tests for the MOCK scan generator: the same host always gives the same result, values stay in
// the ranges the frontend mock uses, and the output matches the frontend mock's values.
public class StaticScanGeneratorTests
{
    private static readonly DateTimeOffset Now = new(2026, 10, 14, 9, 30, 0, TimeSpan.Zero);

    private static StaticScanGenerator CreateGenerator() => new(new FixedTimeProvider(Now));

    // The same host (however it is spelled in the URL) gives the same stack, confidence and pages.
    [Fact]
    public async Task Same_host_gives_the_same_result()
    {
        var generator = CreateGenerator();

        var a = await generator.GenerateAsync(new Uri("https://example.com/"), CancellationToken.None);
        var b = await generator.GenerateAsync(new Uri("https://www.EXAMPLE.com/docs?x=1#top"), CancellationToken.None);
        var c = await generator.GenerateAsync(new Uri("http://example.com:8080/other"), CancellationToken.None);

        foreach (var other in new[] { b, c })
        {
            Assert.Equal(a.Confidence, other.Confidence);
            Assert.Equal(a.Pages, other.Pages);
            Assert.Equal(a.DurationMs, other.DurationMs);
            Assert.Equal(a.Tech.Select(t => (t.Name, t.Highlighted)), other.Tech.Select(t => (t.Name, t.Highlighted)));
        }
    }

    // Different hosts can give different results (the hash really is used).
    [Fact]
    public async Task Different_hosts_can_give_different_results()
    {
        var generator = CreateGenerator();
        var seen = new HashSet<string>();

        foreach (var host in new[] { "example.com", "github.com", "nextjs.org", "docs.python.org", "a.b" })
        {
            var scan = await generator.GenerateAsync(new Uri($"https://{host}/"), CancellationToken.None);
            seen.Add($"{scan.Confidence}/{scan.Pages}/{scan.Tech[0].Name}");
        }

        Assert.True(seen.Count > 1);
    }

    // Values stay in the mock's ranges for many different hosts.
    [Fact]
    public async Task Values_are_in_plausible_ranges()
    {
        var generator = CreateGenerator();

        for (var i = 0; i < 200; i++)
        {
            var scan = await generator.GenerateAsync(new Uri($"https://site-{i}.example.org/"), CancellationToken.None);

            Assert.InRange(scan.Confidence, 88, 99);
            Assert.InRange(scan.Pages, 4, 23);
            Assert.Equal(StaticScanGenerator.MockDurationMs, scan.DurationMs);
            Assert.InRange(scan.Tech.Count, 4, 5);
            Assert.All(scan.Tech, t => Assert.False(string.IsNullOrWhiteSpace(t.Name)));
            Assert.Equal(Enumerable.Range(0, scan.Tech.Count).Select(index => index < 3), scan.Tech.Select(t => t.Highlighted));
            Assert.False(string.IsNullOrWhiteSpace(scan.Markdown));
        }
    }

    // The hash and everything derived from it match what the frontend mock computes
    // (values taken from running frontend/app/functions/data/static/mock-scan.ts's hash in Node).
    [Theory]
    [InlineData("example.com", 1125968678u, 90, 22, "Astro 4")]
    [InlineData("github.com", 1228281881u, 93, 5, "Nuxt 3")]
    [InlineData("nextjs.org", 26556399u, 91, 23, "Django")]
    [InlineData("docs.python.org", 518412198u, 94, 22, "Astro 4")]
    [InlineData("xn--bcher-kva.de", 219606573u, 97, 17, "Astro 4")]
    [InlineData("a.b", 277607692u, 92, 16, "WordPress 6")]
    public async Task Output_matches_the_frontend_mock(string host, uint expectedHash, int confidence, int pages, string firstTech)
    {
        Assert.Equal(expectedHash, StaticScanGenerator.Hash(host));

        var scan = await CreateGenerator().GenerateAsync(new Uri($"https://{host}/"), CancellationToken.None);

        Assert.Equal(confidence, scan.Confidence);
        Assert.Equal(pages, scan.Pages);
        Assert.Equal(firstTech, scan.Tech[0].Name);
    }

    // The Markdown is the same document the frontend mock builds (checked line by line for example.com).
    [Fact]
    public async Task Markdown_matches_the_frontend_mock_document()
    {
        var scan = await CreateGenerator().GenerateAsync(new Uri("https://www.example.com/docs"), CancellationToken.None);

        var expected = string.Join(
            "\n",
            "# example.com Documentation",
            "",
            "> Generated by Project MD from https://www.example.com/docs",
            "",
            "## Overview",
            "",
            "- **URL:** https://www.example.com/docs",
            "- **Scanned:** 2026-10-14",
            "- **Pages documented:** 22",
            "- **Confidence:** 90%",
            "",
            "## Tech Stack",
            "",
            "- **Framework:** Astro 4",
            "- **Hosting:** Cloudflare Pages",
            "- **Styling:** Tailwind CSS",
            "- **Language:** TypeScript",
            "",
            "## Site Structure",
            "",
            "```",
            "├── /",
            "├── /docs",
            "├── /pricing",
            "└── /blog",
            "```",
            "");

        Assert.Equal(expected, scan.Markdown);
        Assert.Equal(new[] { "Astro 4", "Cloudflare Pages", "Tailwind CSS", "TypeScript" }, scan.Tech.Select(t => t.Name));
        Assert.Equal(new[] { true, true, true, false }, scan.Tech.Select(t => t.Highlighted));
    }

    // A cancelled request does not produce a scan.
    [Fact]
    public async Task Cancelled_token_is_respected()
    {
        using var cts = new CancellationTokenSource();
        await cts.CancelAsync();

        await Assert.ThrowsAnyAsync<OperationCanceledException>(
            () => CreateGenerator().GenerateAsync(new Uri("https://example.com/"), cts.Token));
    }
}
